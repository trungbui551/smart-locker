-- Migration M2: Bảng tủ khóa (lockers), ngăn tủ theo kích cỡ (compartments) và đơn giao nhận (deliveries)
-- Tương thích cả PostgreSQL 16 và H2 (cho CI test).

CREATE TABLE lockers (
    id VARCHAR(20) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    location VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'ONLINE',
    last_heartbeat_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE compartments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locker_id VARCHAR(20) NOT NULL,
    number INTEGER NOT NULL,
    size VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'FREE',
    CONSTRAINT fk_compartment_locker FOREIGN KEY (locker_id) REFERENCES lockers (id) ON DELETE CASCADE,
    CONSTRAINT uq_locker_compartment_number UNIQUE (locker_id, number)
);

CREATE INDEX idx_compartments_locker_size_status ON compartments (locker_id, size, status);

CREATE TABLE deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id BIGINT NOT NULL,
    recipient_id BIGINT NOT NULL,
    compartment_id BIGINT NOT NULL,
    package_size VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE,
    picked_up_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_delivery_courier FOREIGN KEY (courier_id) REFERENCES users (id),
    CONSTRAINT fk_delivery_recipient FOREIGN KEY (recipient_id) REFERENCES users (id),
    CONSTRAINT fk_delivery_compartment FOREIGN KEY (compartment_id) REFERENCES compartments (id)
);

CREATE INDEX idx_deliveries_recipient ON deliveries (recipient_id);
CREATE INDEX idx_deliveries_courier ON deliveries (courier_id);
CREATE INDEX idx_deliveries_status ON deliveries (status);
