-- Migration M3: Bảng otp_codes (mã OTP băm + mã hóa an toàn cho chủ đơn, hạn 24h, khóa sau 3 lần sai)
-- Tương thích cả PostgreSQL 16 và H2 (cho CI test).

CREATE TABLE otp_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT NOT NULL UNIQUE,
    code_hash VARCHAR(128) NOT NULL,
    code_encrypted VARCHAR(255),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked BOOLEAN NOT NULL DEFAULT FALSE,
    resend_count INTEGER NOT NULL DEFAULT 0,
    last_sent_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_otp_delivery FOREIGN KEY (delivery_id) REFERENCES deliveries (id) ON DELETE CASCADE
);

CREATE INDEX idx_otp_codes_delivery_id ON otp_codes (delivery_id);
